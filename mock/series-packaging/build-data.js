// Builds data.js for the mock from the real catalogue: ALL_COURSES and SERIES in
// landing-page/courses.html (the public catalogue) and the published dates in
// webhook/main.py (COURSES). Run from the repo root: node mock/series-packaging/build-data.js
const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..', '..');
const html = fs.readFileSync(path.join(root, 'landing-page/courses.html'), 'utf8');
const grab = (start, end) => {
  const i = html.indexOf(start);
  const j = html.indexOf(end, i);
  return html.slice(i + start.length - 1, j + 2);
};
const ALL = eval('(' + grab('const ALL_COURSES = [', '\n];') + ')');
const SERIES = eval('(' + grab('const SERIES = {', '\n};') + ')');
const py = fs.readFileSync(path.join(root, 'webhook/main.py'), 'utf8');
const published = {};
for (const m of py.matchAll(/"(MER-[A-Z]+-\d+)":\s*\{[^}]*"published":\s*"(\d{4}-\d{2}-\d{2})"/g)) published[m[1]] = m[2];
const courses = ALL.map(c => ({
  id: c.id, strand: c.strand, hours: c.hours, where: c.where, title: c.title,
  desc: c.desc, objectives: c.objectives || [], series: c.series || '', part: c.part || 0, free: !!c.free,
  published: published[c.id] || '',
}));
const missing = courses.filter(c => !c.published).map(c => c.id);
if (missing.length) console.warn('No published date in main.py for', missing.join(', '));
fs.writeFileSync(path.join(__dirname, 'data.js'),
  '// Generated by build-data.js from landing-page/courses.html and webhook/main.py. Do not edit.\n' +
  'window.MOCK_DATA = ' + JSON.stringify({ series: SERIES, courses }, null, 1) + ';\n');
console.log(courses.length, 'courses,', Object.keys(SERIES).length, 'series');
