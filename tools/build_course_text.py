#!/usr/bin/env python3
"""Regenerates webhook/course_text.py from the public catalogue in landing-page/courses.html.

The app's catalogue (COURSES in webhook/main.py) holds titles, hours and dates. The
member area's course and series pages also show each course's description, learning
objectives, strand and where it applies, which live in the ALL_COURSES array on the
public courses page. This script copies them into a Python module so the app never has
to parse the site at request time, and tests/test_platform.py checks the two agree.

Run from the repo root after editing courses.html:  python3 tools/build_course_text.py
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SITE = ROOT / "landing-page" / "courses.html"
OUT = ROOT / "webhook" / "course_text.py"


def _tokens(src: str):
    i, n = 0, len(src)
    while i < n:
        ch = src[i]
        if ch.isspace():
            i += 1
        elif src.startswith("//", i):
            i = src.find("\n", i)
            i = n if i < 0 else i
        elif ch in "'\"":
            j, out = i + 1, []
            while src[j] != ch:
                if src[j] == "\\":
                    out.append({"n": "\n", "'": "'", '"': '"', "\\": "\\"}.get(src[j + 1], src[j + 1]))
                    j += 2
                else:
                    out.append(src[j]); j += 1
            yield ("str", "".join(out)); i = j + 1
        elif ch in "[]{},:":
            yield (ch, ch); i += 1
        else:
            m = re.match(r"[A-Za-z_$][\w$]*|-?\d+(?:\.\d+)?", src[i:])
            if not m:
                raise ValueError(f"cannot read courses.html at: {src[i:i+40]!r}")
            t = m.group(0)
            yield (("num", float(t)) if re.match(r"-?\d", t) else ("id", t)); i += len(t)


def _parse(tokens):
    def value(tok):
        kind, v = tok
        if kind == "str" or kind == "num":
            return v
        if kind == "id":
            return {"true": True, "false": False, "null": None}[v]
        if kind == "[":
            out = []
            tok = next(tokens)
            while tok[0] != "]":
                out.append(value(tok)); tok = next(tokens)
                if tok[0] == ",": tok = next(tokens)
            return out
        if kind == "{":
            out = {}
            tok = next(tokens)
            while tok[0] != "}":
                key = tok[1]; assert next(tokens)[0] == ":"
                out[key] = value(next(tokens)); tok = next(tokens)
                if tok[0] == ",": tok = next(tokens)
            return out
        raise ValueError(tok)
    return value(next(tokens))


def read_site_courses() -> list[dict]:
    html = SITE.read_text(encoding="utf-8")
    arr = "[" + html.split("const ALL_COURSES = [", 1)[1].split("\n];", 1)[0] + "\n]"
    return _parse(_tokens(arr))


def main() -> None:
    courses = read_site_courses()
    text = {c["id"]: {"strand": c["strand"], "where": c["where"], "desc": c["desc"],
                      "objectives": list(c.get("objectives") or [])} for c in courses}
    body = json.dumps(text, indent=1, ensure_ascii=False)
    OUT.write_text(
        '"""Course descriptions, objectives, strand and where-it-applies codes, copied from the\n'
        "public catalogue (landing-page/courses.html, ALL_COURSES) for the member area's course\n"
        "and series pages. GENERATED by tools/build_course_text.py: edit courses.html, then run\n"
        'that script. tests/test_platform.py fails if the two drift apart."""\n\n'
        f"COURSE_TEXT = {body}\n", encoding="utf-8")
    print(f"{len(text)} courses written to {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
